-- Restore verified names for referenced entities without claiming positions.
-- Source: pfQuest 104f35678ca39ab1fb78b655f815cc7016f5e0c8 (MIT).
-- Usage: lua5.1 tools/build_reference_data.lua PFQUEST ID_LIST OUTPUT
local PF = arg[1] or "tools/fixtures/reference-pfquest"
local INPUT = arg[2] or "tools/reference_ids.tsv"
local OUTPUT = arg[3] or "WaypointTracker_Data/ReferenceData.lua"
pfDB = { units = {}, objects = {}, items = {} }
for _, kind in ipairs({ "units", "objects", "items" }) do
    dofile(PF .. "/db/enUS/" .. kind .. ".lua")
end
if arg[4] then
    -- A compact independent name fixture for reproducing this supplement.
    local selected = { units = {}, objects = {}, items = {} }
    local lookup = { U = "units", O = "objects", I = "items" }
    for line in io.lines(INPUT) do
        local kind, id = line:match("^([UOI])\t(%d+)$")
        if kind then selected[lookup[kind]][tonumber(id)] = pfDB[lookup[kind]].enUS[tonumber(id)] end
    end
    for kind, names in pairs(selected) do
        local f = assert(io.open(arg[4] .. "/db/enUS/" .. kind .. ".lua", "w"))
        f:write("-- pfQuest 104f35678ca39ab1fb78b655f815cc7016f5e0c8 (MIT), referenced names.\n")
        f:write("pfDB." .. kind .. ".enUS = {\n")
        local ids = {}
        for id in pairs(names) do ids[#ids + 1] = id end
        table.sort(ids)
        for _, id in ipairs(ids) do f:write(("[%d]=%q,\n"):format(id, names[id])) end
        f:write("}\n"); f:close()
    end
end
local rows = { "WTL1\tpfquest-references\t1" }
local kinds = { U = "units", O = "objects", I = "items" }
for line in io.lines(INPUT) do
    local kind, id = line:match("^([UOI])\t(%d+)$")
    if kind then
        local name = pfDB[kinds[kind]].enUS[tonumber(id)]
        if type(name) == "string" and name ~= "" then
            name = name:gsub("[\t\r\n]", " "):gsub("%]==%]", "] ==]")
            local f = kind == "U" and { "N", id, name, "", "", "", "", "" }
                or kind == "O" and { "O", id, name, "" }
                or { "I", id, name, "", "" }
            rows[#rows + 1] = table.concat(f, "\t")
        else
            print("NON_ROUTABLE " .. kind .. id .. ": no verified pfQuest name")
        end
    end
end
local out = assert(io.open(OUTPUT, "w"))
out:write("-- Generated by tools/build_reference_data.lua from pfQuest\n")
out:write("-- 104f35678ca39ab1fb78b655f815cc7016f5e0c8 (MIT). Do not edit.\n")
out:write("-- Named references only: no verified Forever positions. The Find window\n")
out:write("-- uses its existing no-location result until the client supplies a location.\n")
out:write("local D = WaypointTrackerData\nif not D then\n    return\nend\n")
out:write("local references = [==[\n" .. table.concat(rows, "\n") .. "\n]==]\n")
out:write("D.curated = (D.curated or \"\") .. \"\\n\" .. references\n")
out:close()
print(("REFERENCE DEFINITIONS: %d named targets without coordinates"):format(#rows - 1))
